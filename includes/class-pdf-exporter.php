<?php
/**
 * Dependency-free PDF conversation export.
 *
 * Generates a standards-compliant PDF 1.4 document using only PHP string
 * building. Helvetica core fonts + WinAnsi encoding cover ASCII and cp1252
 * characters; anything outside cp1252 is transliterated so the file always
 * opens correctly. Internal notes are excluded by default.
 *
 * @package LiveDesk
 */

namespace LiveDesk;

defined( 'ABSPATH' ) || exit;

/**
 * Class PDF_Exporter
 */
class PDF_Exporter {

	/** @var array Lines to render (each line is array(text, style)). */
	private $lines = array();

	/** @var float Page width (pt). */
	private $pw = 595.28; // A4 width.

	/** @var float Page height (pt). */
	private $ph = 841.89;

	/** @var float Left margin. */
	private $margin = 48;

	/** @var float Current y cursor. */
	private $y = 0;

	/**
	 * Build PDF bytes for a conversation.
	 *
	 * @param object $conversation Conversation row (with visitor_name/email).
	 * @param array  $messages     Message rows.
	 * @param array  $notes        Internal notes (excluded by default).
	 * @param bool   $include_notes Include notes.
	 * @return string PDF bytes.
	 */
	public static function render( $conversation, $messages, $notes = array(), $include_notes = false ) {
		$exporter = new self();
		$exporter->compose( $conversation, $messages, $notes, $include_notes );
		return $exporter->output();
	}

	/**
	 * Compose document content lines.
	 *
	 * @param object $conversation  Conversation row.
	 * @param array  $messages      Messages.
	 * @param array  $notes         Notes.
	 * @param bool   $include_notes Include notes.
	 * @return void
	 */
	private function compose( $conversation, $messages, $notes, $include_notes ) {
		$site = get_bloginfo( 'name' );

		$this->lines[] = array( $site, 'title' );
		$this->lines[] = array( __( 'Conversation Transcript', 'livedesk' ), 'subtitle' );
		$this->lines[] = array( '', 'gap' );

		$this->lines[] = array( __( 'Visitor', 'livedesk' ) . ': ' . $conversation->visitor_name, 'meta' );
		$this->lines[] = array( __( 'Email', 'livedesk' ) . ': ' . $conversation->visitor_email, 'meta' );
		$this->lines[] = array( __( 'Reference', 'livedesk' ) . ': ' . $conversation->ticket_ref, 'meta' );
		$this->lines[] = array( __( 'Status', 'livedesk' ) . ': ' . Conversation_Manager::status_label( $conversation->status ), 'meta' );
		$this->lines[] = array( __( 'Started', 'livedesk' ) . ': ' . Utils::format_datetime( $conversation->created_at ), 'meta' );
		if ( $conversation->agent_id ) {
			$this->lines[] = array( __( 'Agent', 'livedesk' ) . ': ' . Permissions::agent_display_name( (int) $conversation->agent_id, 'display_name' ), 'meta' );
		}
		$this->lines[] = array( __( 'Exported', 'livedesk' ) . ': ' . Utils::format_datetime( Utils::now_gmt() ), 'meta' );
		$this->lines[] = array( '', 'rule' );

		foreach ( $messages as $message ) {
			$type = (string) $message->sender_type;
			if ( 'visitor' === $type ) {
				$visitor = Visitor_Manager::get( (int) $message->sender_id );
				$name    = $visitor ? $visitor->name : __( 'Visitor', 'livedesk' );
				$who     = sprintf( '%s (%s)', $name, __( 'Visitor', 'livedesk' ) );
			} else {
				$who = sprintf( '%s (%s)', Permissions::agent_display_name( (int) $message->sender_id, 'display_name' ), __( 'Agent', 'livedesk' ) );
			}
			$this->lines[] = array( '[' . Utils::format_datetime( $message->created_at, 'Y-m-d H:i' ) . '] ' . $who, 'sender' );

			$body = trim( (string) $message->body );
			foreach ( explode( "\n", $body ) as $body_line ) {
				$this->lines[] = array( $body_line, 'body' );
			}

			$attachments = Attachment_Manager::for_message( (int) $message->id );
			foreach ( $attachments as $att ) {
				$this->lines[] = array( __( 'Attachment', 'livedesk' ) . ': ' . $att->original_name . ' (' . size_format( (int) $att->file_size ) . ')', 'attachment' );
			}
			$this->lines[] = array( '', 'gap' );
		}

		if ( $include_notes && $notes ) {
			$this->lines[] = array( __( 'Internal notes', 'livedesk' ), 'subtitle' );
			foreach ( $notes as $note ) {
				$this->lines[] = array( '[' . Utils::format_datetime( $note->created_at, 'Y-m-d H:i' ) . '] ' . Permissions::agent_display_name( (int) $note->author_id, 'display_name' ), 'sender' );
				foreach ( explode( "\n", (string) $note->content ) as $note_line ) {
					$this->lines[] = array( $note_line, 'body' );
				}
				$this->lines[] = array( '', 'gap' );
			}
		}

		$this->lines[] = array( '— ' . sprintf( /* translators: %s: site name */ __( 'Generated by %s', 'livedesk' ), 'LiveDesk' ) . ' —', 'footer' );
	}

	/**
	 * Convert UTF-8 text to WinAnsi (cp1252) with fallbacks.
	 *
	 * @param string $text Text.
	 * @return string
	 */
	private static function encode( $text ) {
		$text = (string) $text;
		// Normalize common smart punctuation to ASCII.
		$text = str_replace(
			array( '’', '‘', '“', '”', '–', '—', '…', '•' ),
			array( "'", "'", '"', '"', '-', '-', '...', '*' ),
			$text
		);
		if ( function_exists( 'iconv' ) ) {
			$converted = @iconv( 'UTF-8', 'CP1252//TRANSLIT//IGNORE', $text ); // phpcs:ignore WordPress.PHP.NoSilencedErrors
			if ( false !== $converted ) {
				$text = $converted;
			}
		}
		return preg_replace( '/[^\x20-\x7E\xA0-\xFF\r\n\t]/', '?', $text );
	}

	/**
	 * Escape for PDF string literal.
	 *
	 * @param string $text Text.
	 * @return string
	 */
	private static function pdf_string( $text ) {
		$text = self::encode( $text );
		return str_replace( array( '\\', '(', ')', "\r" ), array( '\\\\', '\\(', '\\)', '' ), $text );
	}

	/**
	 * Approximate Helvetica width of a string in points.
	 *
	 * @param string $text Text.
	 * @param float  $size Font size.
	 * @param bool   $bold Bold.
	 * @return float
	 */
	private static function text_width( $text, $size, $bold = false ) {
		$len   = strlen( $text );
		$width = $len * $size * ( $bold ? 0.55 : 0.50 );
		return $width;
	}

	/**
	 * Wrap text to a max width.
	 *
	 * @param string $text  Text.
	 * @param float  $max   Max width in points.
	 * @param float  $size  Font size.
	 * @param bool   $bold  Bold.
	 * @return array
	 */
	private static function wrap( $text, $max, $size, $bold = false ) {
		$text = str_replace( "\t", '    ', (string) $text );
		if ( '' === trim( $text ) ) {
			return array( '' );
		}
		$words   = preg_split( '/ +/', $text );
		$lines   = array();
		$current = '';
		foreach ( $words as $word ) {
			$candidate = '' === $current ? $word : $current . ' ' . $word;
			if ( self::text_width( $candidate, $size, $bold ) > $max && '' !== $current ) {
				$lines[] = $current;
				$current = $word;
			} else {
				$current = $candidate;
			}
		}
		if ( '' !== $current ) {
			$lines[] = $current;
		}
		return $lines;
	}

	/**
	 * Render content streams per page.
	 *
	 * @return array Page streams.
	 */
	private function paginate() {
		$pages    = array();
		$page     = array();
		$y        = $this->ph - $this->margin;
		$bottom   = $this->margin;
		$maxw     = $this->pw - ( $this->margin * 2 );

		$styles = array(
			'title'      => array( 20, true, 34 ),
			'subtitle'   => array( 13, false, 22 ),
			'meta'       => array( 10, false, 15 ),
			'rule'       => array( 10, false, 14 ),
			'sender'     => array( 10.5, true, 15 ),
			'body'       => array( 10.5, false, 14.5 ),
			'attachment' => array( 9.5, false, 13.5 ),
			'gap'        => array( 10, false, 12 ),
			'footer'     => array( 9, false, 14 ),
		);

		foreach ( $this->lines as $entry ) {
			list( $text, $style ) = $entry;
			$style_data           = isset( $styles[ $style ] ) ? $styles[ $style ] : $styles['body'];
			list( $size, $bold, $leading ) = $style_data;

			if ( 'rule' === $style ) {
				$page[] = array( 'rule', $y );
				$y     -= $leading;
				continue;
			}

			$wrapped = self::wrap( $text, $maxw, $size, $bold );
			foreach ( $wrapped as $line ) {
				if ( $y < $bottom ) {
					$pages[] = $page;
					$page    = array();
					$y       = $this->ph - $this->margin;
				}
				$page[] = array( 'text', $y, $line, $size, $bold );
				$y     -= $leading;
			}
		}
		$pages[] = $page;
		return $pages;
	}

	/**
	 * Build the final PDF.
	 *
	 * @return string
	 */
	private function output() {
		$pages   = $this->paginate();
		$objects = array(); // 1-based object list.

		// 1: Catalog, 2: Pages, 3: Font regular, 4: Font bold.
		$kids = array();
		$pid  = 6; // 5 = document info dictionary.
		foreach ( $pages as $page_index => $page ) {
			$kids[] = $pid . ' 0 R';

			$stream = "";
			foreach ( $page as $item ) {
				if ( 'rule' === $item[0] ) {
					$y      = $item[1];
					$stream .= sprintf( "0.75 w\n%.2F %.2F m\n%.2F %.2F l\nS\n", $this->margin, $y, $this->pw - $this->margin, $y );
					continue;
				}
				list( , $y, $line, $size, $bold ) = $item;
				$font   = $bold ? '/F2' : '/F1';
				$stream .= sprintf( "BT %s %.2F Tf 1 0 0 1 %.2F %.2F Tm (%s) Tj ET\n", $font, $size, $this->margin, $y, self::pdf_string( $line ) );
			}
			// Footer page number.
			$label   = sprintf( '%d / %d', $page_index + 1, count( $pages ) );
			$stream .= sprintf( "BT /F1 8 Tf 1 0 0 1 %.2F %.2F Tm (%s) Tj ET\n", $this->pw - 90, 24, self::pdf_string( $label ) );

			$page_obj = $pid;
			$content_id = $pid + 1;
			$objects[ $page_obj ] = sprintf(
				"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 %.2F %.2F] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents %d 0 R >>",
				$this->pw,
				$this->ph,
				$content_id
			);
			$objects[ $content_id ] = "<< /Length " . strlen( $stream ) . " >>\nstream\n" . $stream . "endstream";
			$pid += 2;
		}

		$objects[1] = "<< /Type /Catalog /Pages 2 0 R >>";
		$objects[2] = "<< /Type /Pages /Kids [" . implode( ' ', $kids ) . "] /Count " . count( $pages ) . " >>";
		$objects[3] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>";
		$objects[4] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>";
		$objects[5] = "<< /Producer (LiveDesk) /Creator (LiveDesk Live Chat) >>";

		ksort( $objects );

		$pdf     = "%PDF-1.4\n%\xE2\xE3\xCF\xD3\n";
		$offsets = array();
		$max     = max( array_keys( $objects ) );
		for ( $i = 1; $i <= $max; $i++ ) {
			if ( ! isset( $objects[ $i ] ) ) {
				continue;
			}
			$offsets[ $i ] = strlen( $pdf );
			$pdf          .= $i . " 0 obj\n" . $objects[ $i ] . "\nendobj\n";
		}

		$xref = strlen( $pdf );
		$pdf .= "xref\n0 " . ( $max + 1 ) . "\n";
		$pdf .= "0000000000 65535 f \n";
		for ( $i = 1; $i <= $max; $i++ ) {
			if ( isset( $offsets[ $i ] ) ) {
				$pdf .= sprintf( "%010d 00000 n \n", $offsets[ $i ] );
			} else {
				$pdf .= "0000000000 65535 f \n";
			}
		}
		$pdf .= "trailer\n<< /Size " . ( $max + 1 ) . " /Root 1 0 R /Info 5 0 R >>\nstartxref\n" . $xref . "\n%%EOF";
		return $pdf;
	}
}
